insert into public.districts (city_id, slug, names, wikidata_id, centroid)
select c.id, d.slug, jsonb_build_object('tr', d.name, 'en', d.name), d.qid,
       extensions.st_setsrid(extensions.st_makepoint(d.lon, d.lat), 4326)::extensions.geography
  from d
  join public.cities c on c.slug = d.province
on conflict (city_id, slug) do update
  set wikidata_id = excluded.wikidata_id, centroid = excluded.centroid;

-- ---- One read for every active province and its districts ----------------------------------------------------------
-- 973 districts are more than PostgREST returns from one table read (max_rows is 100 locally, 1000 on hosted), and the
-- app wants them nested anyway. Security invoker: the read policies of both tables still decide what is returned.
create function public.catalog_places()
returns jsonb
language sql
stable
security invoker
set search_path = ''
as $$
  select coalesce(jsonb_agg(jsonb_build_object(
           'id', c.id, 'slug', c.slug, 'names', c.names, 'timezone', c.timezone,
           'districts', coalesce((
             select jsonb_agg(jsonb_build_object('id', d.id, 'slug', d.slug, 'names', d.names) order by d.slug)
               from public.districts d
              where d.city_id = c.id and d.is_active), '[]'::jsonb)
         ) order by c.slug), '[]'::jsonb)
    from public.cities c
   where c.is_active;
$$;

revoke all on function public.catalog_places() from public;
grant execute on function public.catalog_places() to anon, authenticated;
