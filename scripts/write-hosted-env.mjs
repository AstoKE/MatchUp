// Writes apps/app/.env.local for the HOSTED Supabase project linked with `supabase link`
// (`pnpm env:local` switches back to the local stack). Only PUBLIC values are written: the project URL
// and its publishable (or legacy anon) key. Secret / service-role keys returned by the CLI are never
// written or printed. The file is git-ignored (.env.*).
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

let ref;
try {
  ref = readFileSync('supabase/.temp/project-ref', 'utf8').trim();
} catch {
  console.error('No linked project. Run: pnpm exec supabase link --project-ref <ref>');
  process.exit(1);
}
if (!/^[a-z0-9]{20}$/.test(ref)) {
  console.error('supabase/.temp/project-ref does not look like a project ref.');
  process.exit(1);
}

const raw = execSync(`pnpm exec supabase projects api-keys --project-ref ${ref} -o json`, {
  encoding: 'utf8',
  stdio: ['ignore', 'pipe', 'ignore'],
});
const keys = JSON.parse(raw.slice(raw.indexOf('[')));
const publishable = keys.find((k) => k.type === 'publishable' && typeof k.api_key === 'string');
const anon = keys.find((k) => k.name === 'anon' && typeof k.api_key === 'string');
const publicKey = (publishable ?? anon)?.api_key;
if (!publicKey || publicKey.startsWith('sb_secret_')) {
  console.error('Could not find a publishable/anon key for the linked project.');
  process.exit(1);
}

// The map style URL carries the founder's tile key, which neither stack knows: keep it across switches.
function keptMapStyle() {
  try {
    const line = readFileSync('apps/app/.env.local', 'utf8')
      .split('\n')
      .find((l) => l.startsWith('EXPO_PUBLIC_MAP_STYLE_URL='));
    return line ?? 'EXPO_PUBLIC_MAP_STYLE_URL=';
  } catch {
    return 'EXPO_PUBLIC_MAP_STYLE_URL=';
  }
}

const lines = [
  '# Generated by scripts/write-hosted-env.mjs: the HOSTED project. Public values only. Do not commit.',
  '# Switch back to the local stack with: pnpm env:local',
  'EXPO_PUBLIC_APP_ENV=development',
  `EXPO_PUBLIC_SUPABASE_URL=https://${ref}.supabase.co`,
  `EXPO_PUBLIC_SUPABASE_ANON_KEY=${publicKey}`,
  'EXPO_PUBLIC_WEB_URL=http://localhost:8081',
  'EXPO_PUBLIC_SENTRY_DSN=',
  // Must match the hosted Auth CAPTCHA setting (off until a Turnstile site key exists).
  'EXPO_PUBLIC_TURNSTILE_SITE_KEY=',
  keptMapStyle(),
  '',
];
writeFileSync('apps/app/.env.local', lines.join('\n'));
console.log(`wrote apps/app/.env.local for the hosted project ${ref} (public values only)`);
