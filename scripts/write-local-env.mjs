// Writes apps/app/.env.local from the running LOCAL Supabase stack (`pnpm db:start` first).
// Only PUBLIC values are written (API URL + anon key). The service-role/secret keys printed by
// `supabase status` are deliberately never read or written — the client must not be able to hold them.
// The file is git-ignored (.env.*).
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const raw = execSync('pnpm exec supabase status -o json', {
  encoding: 'utf8',
  stdio: ['ignore', 'pipe', 'inherit'],
});

const jsonStart = raw.indexOf('{');
const status = JSON.parse(raw.slice(jsonStart));
const apiUrl = status.API_URL;
const anonKey = status.ANON_KEY;
if (!apiUrl || !anonKey) {
  console.error('Could not read API_URL/ANON_KEY. Is the local stack running (pnpm db:start)?');
  process.exit(1);
}

const lines = [
  '# Generated by scripts/write-local-env.mjs — public local-development values only. Do not commit.',
  'EXPO_PUBLIC_APP_ENV=development',
  `EXPO_PUBLIC_SUPABASE_URL=${apiUrl}`,
  `EXPO_PUBLIC_SUPABASE_ANON_KEY=${anonKey}`,
  'EXPO_PUBLIC_WEB_URL=http://localhost:8081',
  'EXPO_PUBLIC_SENTRY_DSN=',
  '',
];
writeFileSync('apps/app/.env.local', lines.join('\n'));
console.log('wrote apps/app/.env.local (public local values only)');
