// Exports every UI string, Turkish next to English, for a native speaker's review (Phase 7 / M5, ROADMAP F-32).
//
//   node scripts/i18n/export-copy.mjs        # writes docs/COPY_REVIEW.md
//
// Legal texts are left out (they are drafts that counsel rewrites). Re-run after copy changes; the reviewer marks
// lines in a copy of the file and the changes go back into apps/app/src/locales.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('../../', import.meta.url).pathname;
const locales = join(root, 'apps/app/src/locales');
const flatten = (obj, prefix = '') =>
  Object.entries(obj).flatMap(([k, v]) =>
    v && typeof v === 'object' ? flatten(v, `${prefix}${k}.`) : [[`${prefix}${k}`, String(v)]],
  );
const cell = (s) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

const namespaces = readdirSync(join(locales, 'tr'))
  .filter((f) => f.endsWith('.json') && f !== 'legal.json')
  .map((f) => f.replace('.json', ''))
  .sort();
let total = 0;
const sections = namespaces.map((ns) => {
  const tr = flatten(JSON.parse(readFileSync(join(locales, 'tr', `${ns}.json`), 'utf8')));
  const en = Object.fromEntries(
    flatten(JSON.parse(readFileSync(join(locales, 'en', `${ns}.json`), 'utf8'))),
  );
  total += tr.length;
  return [
    `## ${ns} (${tr.length})`,
    '',
    '| Key | Türkçe | English |',
    '|---|---|---|',
    ...tr.map(([key, text]) => `| \`${key}\` | ${cell(text)} | ${cell(en[key] ?? '')} |`),
    '',
  ].join('\n');
});
writeFileSync(
  join(root, 'docs/COPY_REVIEW.md'),
  [
    '# Copy review (Turkish and English)',
    '',
    `Generated by \`node scripts/i18n/export-copy.mjs\` (${total} strings in ${namespaces.length} namespaces; the legal drafts are left out). For a native Turkish speaker: check spelling, tone (informal "sen", as everywhere in the app), suffixes after names and numbers, and that nothing reads as a promise the app does not make (bookings, payments, safety). \`{{…}}\` are filled in by the app; keep them as they are.`,
    '',
    ...sections,
  ].join('\n'),
);
console.log(`docs/COPY_REVIEW.md: ${total} strings`);
